/**
 * ExecutionDAO — 执行域（executions/node_executions/node_edges/branch_executions/
 * agent_events/execution_summaries/pipeline_state + 级联删）。
 * P1 B5 票5：better-sqlite3（143 stmt）→ postgres.js（BasePgDAO）。
 *
 * 行形态契约（pg-mappers 出口归一，旧 Row 接口不动直到 B6）：
 *   - *_at: PG timestamptz(Date) ↔ 旧 ISO 文本 —— iso()/isoOrNull()。
 *   - jsonb 列（var_pool/input_values/pipeline_config/outputs/…）↔ 旧 JSON 文本 —— jsonStr()。
 *   - duration/timestamp/tool_duration_ms/duration_ms: PG bigint(string) ↔ 旧 number —— num()/numOrNull()。
 *   - rollback_on_error/tool_is_error: PG boolean ↔ 旧 0/1 —— flag()/bool()（写侧裸 0/1 静默 false 雷区）。
 *   - 读侧 SELECT * 一律经 fromExec/fromNe/fromAe/fromBe/fromEs/fromPs 归一，
 *     调用方与 route 快照零语义漂移。
 *
 * 方言改写（本批）：
 *   - S1 lastInsertRowid → 本 DAO 无 RETURNING 需求，run 语义 { changes }。
 *   - S3 `INSERT OR IGNORE` ×3 → `ON CONFLICT DO NOTHING`（PG 原生，无需冲突目标）。
 *   - S9 insertAgentEventBatch named-@ 逐行循环 + DAO 内事务 → 一条多行 VALUES 批量
 *     （单语句天然原子，事务随形消失）。replaceMergedEvents 复用同一批量构造器。
 *   - datetime('now', '-N days') → now() - make_interval(days => ?::int)。
 *   - julianday(a)-julianday(b) → EXTRACT(EPOCH FROM (a - b)) * 1000。
 *   - DATE(created_at) → to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD')（UTC 口径同旧）。
 *   - CAST(... AS REAL) → ::double precision（REAL 是 float4，保 double 语义）。
 *   - 裸别名进 HAVING（PG 不允许）→ 聚合表达式原地重写（getWorkflowHealth/findFlakyNodeStats）。
 *   - ORDER BY 可空列对齐 SQLite（NULL 最小）：ASC → NULLS FIRST；DESC → NULLS LAST。
 *   - json_patch(RFC7396 merge-patch) ×2 → `COALESCE(var_pool,'{}'::jsonb) || ?::jsonb`。
 *     裁决依据见下方 setLaunchStatus/retireLaunch 注释：两处 patch 均为平铺单键标量值
 *     {"error": <string>}，递归 merge 与顶层键覆盖在此形状下逐键等值，近似安全。
 *   - rowid 单调次序 tiebreak ×4 → 显式 seq 列（pg/schema.sql executions.seq
 *     bigint GENERATED BY DEFAULT AS IDENTITY；schema-parity 例外清单 PG_ONLY_COLS）。
 *     混合期数据由搬迁器按 SQLite rowid 序灌入，seq 单调与旧 tiebreak 同构。
 *   - `pending_hooks != '[]'` 文本比较 → `'[]'::jsonb` 比较。
 *   - tool_is_error = 1 → = true。
 *
 * 事务红线（4 处 DAO 内事务全部 tx 化，体内只经 tx 句柄构造的兄弟实例）：
 *   replaceMergedEvents / cascadeDeleteByWorkspace / cascadeDeleteExecution ——
 *   `const t = new ExecutionDAO(tx)`（同访问域可用 protected q/exec）；体内禁 this.*（池根句柄 = 逃逸提交）。
 *   insertAgentEventBatch 的事务随 S9 多行 VALUES 消灭。
 *   cascadeDeleteByWorkspace 新增 schedule_workspaces.execution_id 置 NULL 先行 ——
 *   PG FK 即时生效（SQLite 侧该 FK 同为 ON，删除序此前只是恰好没踩到）。
 *
 * 混合期（B5→B6）：workspaces 行生产者仍 SQLite —— JOIN workspaces 的读路径
 * （findWorkspacePath、getQueueItems、findByOrgWithWorkspace 等）读 PG 快照表，
 * 与 B4 账本读侧同一已裁决过渡态。executions/pipeline_state/schedules/
 * schedule_workspaces → workspaces(id) 四条 FK 已在 pg/schema.sql 注释撤除
 * （README「B6 FK 恢复清单」登记，schema-parity HYBRID_DROPPED_FKS 同步）。
 */

  async updateExecution(id: string, fields: Partial<ExecutionRow>): Promise<{ changes: number }> {
    const allowed = new Set([
      "status", "gate_status", "var_pool", "progress", "started_at", "completed_at",
      "duration", "global_session_id", "approval_metadata", "interaction_metadata", "chain_retry_count",
      "preset_inputs", "name", "branch", "start_commit_id", "end_commit_id",
      "pipeline_config", "retry_count", "pending_hooks", "resume_attempts",
      "instance_id", "input_values", "budget_snapshot",
      "phase_index", "round_index",
    ])
    const sets: string[] = []
    const vals: unknown[] = []
    for (const [k, v] of Object.entries(fields)) {
      if (k === "id") continue
      if (!allowed.has(k)) throw new Error(`Disallowed column: ${k}`)
      sets.push(`${k} = ?`)
      vals.push(v)
    }
    if (sets.length === 0) return { changes: 0 }
    // PG 同列重复 SET 直接报错（SQLite 静默取后者）—— fields 已带 updated_at 时不再追加
    if (!("updated_at" in fields)) {
      sets.push("updated_at = ?")
      vals.push(new Date().toISOString())
    }
    vals.push(id)
    return await this.exec(`UPDATE executions SET ${sets.join(", ")} WHERE id = ?`, vals)
  }


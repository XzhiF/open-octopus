/** jsonb 目标的入侧规范化：空/空白文本 → 回退值（PG jsonb 拒收 ''，SQLite 旧层宽容）。 */
function jsonIn(v: string | null | undefined, fallback: string | null): string | null {
  if (v == null) return fallback
  const s = v.trim()
  return s.length > 0 ? s : fallback
}

/** outputs 列（jsonb）→ 旧 JSON.parse 语义。 */
function parseJsonObject(v: unknown): Record<string, unknown> | null {
  if (v === null || v === undefined) return null
  if (typeof v === "object") return v as Record<string, unknown>
  if (typeof v === "string") {
    if (!v) return null
    try { return JSON.parse(v) as Record<string, unknown> } catch { return null }
  }
  return null
}


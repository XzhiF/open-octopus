  /** Event types produced by the compaction merge — stored as full JSON for round-trip fidelity. */
  private static MERGED_EVENT_TYPES = new Set([
    "thinking_block", "text_block", "tool_call",
    "bash_output", "bash_stderr", "python_output", "python_stderr",
  ])

  /** Replace all agent events for a node with merged (compacted) events.
   *  [票5 事务红线] tx 体内全部经 `new ExecutionDAO(tx)`（t.*）—— this.* = 池根句柄，
   *  写入逃逸且照常提交（base-pg.ts 反模式钉桩）。合并插入改多行 VALUES 单语句。 */
  async replaceMergedEvents(executionId: string, nodeId: string, mergedEvents: any[]): Promise<void> {
    await this.transaction(async (tx) => {
      const t = new ExecutionDAO(tx)
      const neId = `${executionId}-${nodeId}`
      // Delete old fragmented events for this node, but preserve harness_* and intervention_result events
      await t.exec("DELETE FROM agent_events WHERE node_execution_id = ? AND event_type NOT LIKE 'harness_%' AND event_type != 'intervention_result'", [neId])
      // 权威轮次窗口：llm_calls 每回合一条、ts 与回合精确对齐，且在本方法（节点收尾
      // 后触发）之前已由 onNodeEnd 落库。合并块不带 turnIndex → 按窗口派生回合，
      // 否则旧逻辑 `e.turnIndex ?? 1` 会把任意多回合一律压成 turn_index=1。
      const callRows = await t.q<{ turn_index: number; timestamp: PgNum }>(
        "SELECT turn_index, timestamp FROM llm_calls WHERE node_execution_id = ? ORDER BY timestamp",
        [neId],
      )
      const bounds = buildTurnBoundaries(callRows.map(r => ({ turn_index: r.turn_index, timestamp: num(r.timestamp) })))
      // Build merged events（timestamp 列是 epoch-ms —— 同旧注释：ISO 串直存的历史 bug 已收口）
      const rows: AgentEventRow[] = []
      for (let i = 0; i < mergedEvents.length; i++) {
        const e = mergedEvents[i]
        const ts = toEpochMs(e.startedAt ?? e.timestamp) || Date.now()
        // For merged block types, store the full event as JSON so the read path
        // can round-trip without losing startedAt/completedAt/toolName/etc.
        const isMergedType = ExecutionDAO.MERGED_EVENT_TYPES.has(e.event)
        const content = isMergedType
          ? JSON.stringify(e)
          : (e.content ?? e.line ?? (e.lines ? e.lines.join("\n") : null))
        // 与读侧 assignTurnsToEvents 同一真相源(llm_calls 时间窗)，写读一致。
        const evMs = ts
        const turn = (bounds.length > 0 && evMs > 0) ? deriveTurnForTs(bounds, evMs) : (e.turnIndex ?? 1)
        rows.push({
          node_execution_id: neId, event_order: i, turn_index: turn, event_type: e.event, timestamp: ts,
          content, content_length: content ? content.length : 0,
          tool_call_id: e.toolCallId ?? null, tool_name: e.toolName ?? null,
          tool_input: e.input ? (typeof e.input === "string" ? e.input : JSON.stringify(e.input)) : null,
          tool_result: e.result ? (typeof e.result === "string" ? e.result : JSON.stringify(e.result)) : null,
          tool_is_error: e.isError ? 1 : 0, tool_duration_ms: e.toolDurationMs ?? null,
          status_value: null, error_code: null, error_message: null,
        })
      }
      if (rows.length > 0) await t.insertAgentEvents(rows, false)
    })
  }


  // ── Cascade delete ──────────────────────────────────────────────

  /** [票5 事务红线] tx 体全程 t.*；新增 schedule_workspaces.execution_id 置 NULL ——
   *  PG 对 executions 的 FK 即时生效，删除被引用行必先解引用（旧 SQLite 同 FK 声明下
   *  该列此前只是恰好没有引用，删除序不变）。 */
  async cascadeDeleteByWorkspace(workspaceId: string): Promise<void> {
    await this.transaction(async (tx) => {
      const t = new ExecutionDAO(tx)
      const execIds = await t.findExecutionIdsForCascade(workspaceId)
      if (execIds.length > 0) {
        const placeholders = execIds.map(() => "?").join(",")
        const vals = execIds
        await t.exec("UPDATE schedule_workspaces SET execution_id = NULL WHERE execution_id IN (SELECT id FROM executions WHERE workspace_id = ?)", [workspaceId])
        await t.exec(`DELETE FROM agent_events WHERE node_execution_id IN (SELECT ne.id FROM node_executions ne WHERE ne.execution_id IN (${placeholders}))`, vals)
        await t.exec(`DELETE FROM llm_calls WHERE node_execution_id IN (SELECT ne.id FROM node_executions ne WHERE ne.execution_id IN (${placeholders}))`, vals)
        await t.exec(`DELETE FROM node_token_usages WHERE node_execution_id IN (SELECT ne.id FROM node_executions ne WHERE ne.execution_id IN (${placeholders}))`, vals)
        await t.exec(`DELETE FROM branch_executions WHERE node_execution_id IN (SELECT ne.id FROM node_executions ne WHERE ne.execution_id IN (${placeholders}))`, vals)
        await t.exec(`DELETE FROM node_edges WHERE execution_id IN (${placeholders})`, vals)
        await t.exec(`DELETE FROM node_executions WHERE execution_id IN (${placeholders})`, vals)
        await t.exec(`DELETE FROM execution_summaries WHERE execution_id IN (${placeholders})`, vals)
        await t.exec(`DELETE FROM schedule_executions WHERE execution_id IN (${placeholders})`, vals)
      }
      await t.exec("DELETE FROM executions WHERE workspace_id = ?", [workspaceId])
    })
  }


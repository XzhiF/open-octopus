  async getDashboardStats(): Promise<{
    total_executions: number; completed_executions: number; failed_executions: number;
    running_executions: number; pending_executions: number; cancelled_executions: number;
    avg_duration_ms: number | null
  }> {
    const row = await this.q1<{
      total_executions: PgNum; completed_executions: PgNum | null; failed_executions: PgNum | null;
      running_executions: PgNum | null; pending_executions: PgNum | null; cancelled_executions: PgNum | null;
      avg_duration_ms: PgNum | null
    }>(`
      WITH root_executions AS (
        SELECT id, status as root_status, duration, completed_at, started_at
        FROM executions WHERE parent_id IS NULL OR parent_id = '0' OR phase_index IS NOT NULL
      ),
      latest_children AS (
        SELECT parent_id, status as child_status,
          ROW_NUMBER() OVER (PARTITION BY parent_id ORDER BY started_at DESC NULLS LAST) as rn
        FROM executions WHERE parent_id IS NOT NULL AND parent_id != '0' AND phase_index IS NULL
      ),
      effective_status AS (
        SELECT r.id, COALESCE(lc.child_status, r.root_status) as status,
          r.duration, r.completed_at, r.started_at
        FROM root_executions r
        LEFT JOIN latest_children lc ON r.id = lc.parent_id AND lc.rn = 1
      )
      SELECT
        COUNT(*) as total_executions,
        SUM(CASE WHEN status = 'completed' THEN 1 ELSE 0 END) as completed_executions,
        SUM(CASE WHEN status = 'failed' THEN 1 ELSE 0 END) as failed_executions,
        SUM(CASE WHEN status = 'running' THEN 1 ELSE 0 END) as running_executions,
        SUM(CASE WHEN status = 'pending' THEN 1 ELSE 0 END) as pending_executions,
        SUM(CASE WHEN status = 'cancelled' THEN 1 ELSE 0 END) as cancelled_executions,
        AVG(COALESCE(duration,
          CASE WHEN completed_at IS NOT NULL AND started_at IS NOT NULL
            THEN EXTRACT(EPOCH FROM (completed_at - started_at)) * 1000
            ELSE NULL END)) as avg_duration_ms
      FROM effective_status
    `)
    return {
      total_executions: num(row?.total_executions),
      completed_executions: num(row?.completed_executions),
      failed_executions: num(row?.failed_executions),
      running_executions: num(row?.running_executions),
      pending_executions: num(row?.pending_executions),
      cancelled_executions: num(row?.cancelled_executions),
      avg_duration_ms: numOrNull(row?.avg_duration_ms),
    }
  }


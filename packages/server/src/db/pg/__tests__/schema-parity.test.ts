/** SQLite 侧存 ISO 串的时间列（*_at / timestamp(ISO) / last_heartbeat / last_injected）→ timestamptz。 */
const ISO_EXTRA = new Set(['knowledge_effectiveness.last_injected', 'scheduler_state.last_heartbeat'])
function isIsoTimestampCol(table: string, col: string): boolean {
  if (EPOCH_MS.has(`${table}.${col}`)) return false
  if (ISO_EXTRA.has(`${table}.${col}`)) return true
  if (col === 'timestamp') return table === 'evolution_log' || table === 'safety_events'
  return col.endsWith('_at')
}

function expectedPgType(table: string, col: string, sqliteType: string): string {
  const key = `${table}.${col}`
  if (sqliteType === 'REAL') return 'double precision'
  if (sqliteType === 'INTEGER') {
    if (IDENTITY.has(key)) return 'bigint'
    if (EPOCH_MS.has(key)) return 'bigint'
    if (BOOL.has(key)) return 'boolean'
    return 'integer'
  }
  if (sqliteType === 'TEXT') {
    if (JSONB.has(key)) return 'jsonb'
    if (isIsoTimestampCol(table, col)) return 'timestamptz'
    return 'text'
  }
  throw new Error(`unmapped SQLite type ${JSON.stringify(sqliteType)} on ${key}`)
}

/** 默认值语义归一：datetime('now')↔now()、剥外层括号/::cast/引号、0/1↔false/true、jsonb 比解析后结构。 */
function normalizeDefault(raw: string | null | undefined, pgType: string): string | null {
  if (raw === null || raw === undefined) return null
  let s = String(raw).trim()
  if (/^null$/i.test(s)) return null
  const paren = s.match(/^\((.*)\)$/s)
  if (paren && !/^\(.*\)$/.test(paren[1])) s = paren[1].trim()
  if (/^datetime\(\s*'now'\s*\)$/i.test(s) || /^now\(\)$/i.test(s)) return 'now()'
  s = s.replace(/::[\w" ]+$/, '')
  const quoted = s.match(/^'((?:[^']|'')*)'$/s)
  const value = quoted ? quoted[1].replace(/''/g, "'") : s
  if (pgType === 'boolean') {
    if (value === '1' || /^true$/i.test(value)) return 'true'
    if (value === '0' || /^false$/i.test(value)) return 'false'
  }
  if (pgType === 'jsonb') {
    return JSON.stringify(JSON.parse(value))
  }
  if (pgType === 'integer' || pgType === 'bigint') return String(Number(value))
  return value
}

interface SqliteCol {
  name: string
  type: string
  notnull: number
  dflt_value: string | null
  pk: number
}

describePg('PG schema parity — per-table/per-column vs SQLite', () => {
  let sqlite: Database.Database
  let pg: PgTestDatabase

  beforeAll(async () => {
    sqlite = new Database(':memory:')
    sqlite.pragma('foreign_keys = ON')
    applySchema(sqlite)
    pg = await createTestDatabase()
  }, 120_000)

  afterAll(async () => {
    sqlite?.close()
    await pg?.close()
  })

  // SQLite :memory: 上 applySchema 后仍有 FTS5 影子表（*_fts_content/_idx/…）与
  // 虚表本体；两侧统一剔除，只比 42 张普通表。
  const isFtsFamily = (n: string): boolean => /_fts(_|$)/.test(n)

  function sqliteTables(): string[] {
    return (sqlite.prepare(
      "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    ).all() as { name: string }[])
      .map(r => r.name)
      .filter(n => !isFtsFamily(n))
  }

  function sqliteCols(table: string): SqliteCol[] {
    return sqlite.prepare(`PRAGMA table_info(${table})`).all() as SqliteCol[]
  }

  interface PgCol {
    column_name: string
    is_nullable: string
    data_type: string
    column_default: string | null
    attidentity: string
    ordinal: number
  }

  async function pgCols(table: string): Promise<PgCol[]> {
    const rows = (await pg.sql`
      SELECT a.attname AS column_name,
             CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END AS is_nullable,
             format_type(a.atttypid, a.atttypmod) AS data_type,
             pg_get_expr(d.adbin, d.adrelid) AS column_default,
             a.attidentity::text AS attidentity,
             a.attnum AS ordinal
      FROM pg_attribute a
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = ${table}::regclass::oid
        AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum
    `) as unknown as PgCol[]
    // format_type 给全称；映射规则表用简称
    return rows.map(r => ({ ...r, data_type: r.data_type === 'timestamp with time zone' ? 'timestamptz' : r.data_type }))
  }

  it('has the same 42 regular tables (PG side minus octopus_schema_version)', async () => {
    const sqliteNames = sqliteTables()
    expect(sqliteNames).toHaveLength(42)
    const pgNames = (await pg.sql`
      SELECT table_name FROM information_schema.tables
      WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
        AND table_name <> 'octopus_schema_version'
      ORDER BY table_name
    `).map(r => r.table_name as string).filter(n => !isFtsFamily(n))
    expect(pgNames).toEqual(sqliteNames)
  })

  it('per-column: name set, nullability, type mapping, default semantics, PK', async () => {
    for (const table of sqliteTables()) {
      const sCols = sqliteCols(table)
      const pCols = await pgCols(table)
      // 列名集合与顺序（顺序非契约，排序后比）
      expect(pCols.map(c => c.column_name).sort(), `${table}: column set`).toEqual(sCols.map(c => c.name).sort())

      for (const sc of sCols) {
        const pc = pCols.find(c => c.column_name === sc.name)
        expect(pc, `${table}.${sc.name}: missing in PG`).toBeDefined()
        if (!pc) continue
        const key = `${table}.${sc.name}`
        const want = expectedPgType(table, sc.name, sc.type)
        expect(pc.data_type, `${key}: type`).toBe(want)
        // 可空性：SQLite 语义 = declared NOT NULL 或 PK（PK 隐含非空）
        const sqliteNullable = sc.notnull === 0 && sc.pk === 0
        expect(pc.is_nullable === 'YES', `${key}: nullability`).toBe(sqliteNullable)
        // 默认值语义
        expect(
          normalizeDefault(pc.column_default, want),
          `${key}: default`,
        ).toEqual(normalizeDefault(sc.dflt_value, want))
        // IDENTITY 纪律：AUTOINCREMENT ↔ attidentity='d'（BY DEFAULT，搬迁票要带原 id）
        expect(pc.attidentity === 'd', `${key}: identity`).toBe(IDENTITY.has(key))
      }
    }
  })

  it('per-table: primary keys match', async () => {
    for (const table of sqliteTables()) {
      const sPk = sqliteCols(table).filter(c => c.pk > 0).sort((a, b) => a.pk - b.pk).map(c => c.name)
      const pPk = (await pg.sql`
        SELECT a.attname AS col
        FROM pg_index i
        JOIN pg_class c ON c.oid = i.indexrelid
        JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid = ${table}::regclass::oid AND i.indisprimary
        ORDER BY array_position(i.indkey::int[], a.attnum)
      `).map(r => r.col as string)
      expect(pPk, `${table}: PK columns`).toEqual(sPk)
    }
  })

  it('per-table: foreign keys match (columns, target, ON DELETE)', async () => {
    const sFks = new Map<string, string[]>()
    for (const table of sqliteTables()) {
      const row = sqlite.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name=?").get(table) as { sql: string }
      const fks: string[] = []
      for (const m of row.sql.matchAll(/FOREIGN KEY \((\w+)\) REFERENCES (\w+)\((\w+)\)( ON DELETE (\w+))?/g)) {
        fks.push(`${m[1]}->${m[2]}(${m[3]})${m[5] ? ':' + m[5].toUpperCase() : ''}`)
      }
      sFks.set(table, fks.sort())
    }
    const pFks = new Map<string, string[]>()
    const rows = (await pg.sql`
      SELECT src.relname AS table,
             (SELECT string_agg(a.attname, ',') FROM pg_attribute a WHERE a.attrelid = fc.conrelid AND a.attnum = ANY(fc.conkey)) AS col,
             tgt.relname AS reftable,
             (SELECT string_agg(a.attname, ',') FROM pg_attribute a WHERE a.attrelid = fc.confrelid AND a.attnum = ANY(fc.confkey)) AS refcol,
             CASE fc.confdeltype WHEN 'a' THEN '' WHEN 'c' THEN ':CASCADE' WHEN 'r' THEN ':RESTRICT' WHEN 'n' THEN ':SET NULL' WHEN 'd' THEN ':SET DEFAULT' ELSE ':' || upper(fc.confdeltype) END AS ondelete
      FROM pg_constraint fc
      JOIN pg_class src ON src.oid = fc.conrelid
      JOIN pg_class tgt ON tgt.oid = fc.confrelid
      WHERE fc.contype = 'f' AND src.relname = ANY(${[...sFks.keys()]}::text[])
    `) as unknown as Array<{ table: string; col: string; reftable: string; refcol: string; ondelete: string }>
    for (const r of rows) {
      const list = pFks.get(r.table) ?? []
      list.push(`${r.col}->${r.reftable}(${r.refcol})${r.ondelete}`)
      pFks.set(r.table, list)
    }
    for (const table of sFks.keys()) {
      expect([...(pFks.get(table) ?? [])].sort(), `${table}: FKs`).toEqual(sFks.get(table))
    }
  })

  it('explicit index parity: names, uniqueness, columns, DESC & partial semantics', async () => {
    const sIdx = (sqlite.prepare(
      "SELECT name, tbl_name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL AND sql LIKE 'CREATE%INDEX%' ORDER BY name",
    ).all() as Array<{ name: string; tbl_name: string; sql: string }>)
      .filter(r => !isFtsFamily(r.tbl_name))
    // 迁移票纪律：索引面 102 条是判据基线；任何一侧加索引必须两侧同改
    expect(sIdx.length).toBe(102)

    const pIdx = (await pg.sql`
      SELECT ic.relname AS name, t.relname AS tbl, i.indisunique AS "unique",
             i.indpred IS NOT NULL AS partial,
             (SELECT string_agg(a.attname, ',' ORDER BY x.pos)
                FROM unnest(i.indkey::int[]) WITH ORDINALITY x(attnum, pos)
                JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = x.attnum
               WHERE x.attnum > 0) AS cols,
             pg_get_indexdef(i.indexrelid) AS fulldef
      FROM pg_index i
      JOIN pg_class ic ON ic.oid = i.indexrelid
      JOIN pg_class t  ON t.oid  = i.indrelid
      JOIN pg_namespace n ON n.oid = ic.relnamespace
      WHERE n.nspname = 'public'
        AND NOT EXISTS (
          SELECT 1 FROM pg_constraint pc WHERE pc.conindid = ic.oid
        )
        AND ic.relname NOT LIKE '%_key'      -- UNIQUE 约束的支撑索引（如 agent_versions）
      ORDER BY ic.relname
    `) as unknown as Array<{ name: string; tbl: string; unique: boolean; partial: boolean; cols: string; fulldef: string }>

    const pByName = new Map(pIdx.map(r => [r.name, r]))
    const sByName = new Map(sIdx.map(r => [r.name, r]))

    // 名字集合完全相等（双向）
    expect([...pByName.keys()].sort()).toEqual([...sByName.keys()].sort())

    for (const [name, s] of sByName) {
      const p = pByName.get(name)!
      const wantUnique = /CREATE UNIQUE/i.test(s.sql)
      expect(p.unique, `${name}: unique`).toBe(wantUnique)
      // 列集合（SQLite 侧从 index_info 取；PG 侧剥掉 DESC/NULLS 修饰再比）
      const info = sqlite.prepare(`PRAGMA index_info(${name})`).all() as Array<{ seqno: number; name: string }>
      const sCols = info.sort((a, b) => a.seqno - b.seqno).map(c => c.name).join(',')
      const pCols = p.cols.replace(/\s+(DESC|ASC)(\s+NULLS\s+(FIRST|LAST))?/gi, '').replace(/\s+/g, ' ').trim().toLowerCase()
      expect(pCols, `${name}: columns`).toBe(sCols.toLowerCase())
      // 部分索引：SQLite 有 WHERE 子句 ↔ PG indispred 非空
      expect(p.partial, `${name}: partial`).toBe(/\bWHERE\b/i.test(s.sql))
      // DESC 语义（部分索引里 created_at DESC 这类）
      if (/\w+ DESC\b/i.test(s.sql)) {
        expect(/DESC/.test(p.fulldef), `${name}: DESC ordering carried over`).toBe(true)
      }
    }
  })

  it('FTS5 placeholders: the 3 virtual tables became plain annotated tables', async () => {
    const names = ['session_memory_fts', 'experiences_fts', 'reports_fts']
    for (const t of names) {
      const row = (await pg.sql`
        SELECT count(*)::int AS n FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = ${t}
      `)[0]
      expect(row.n, `${t}: placeholder exists with columns`).toBeGreaterThan(0)
    }
    // 显式 row_id 列 = FTS5 隐式 rowid 的手工同步契约
    const exp = (await pgCols('experiences_fts')).map(c => c.column_name)
    expect(exp).toEqual(['row_id', 'skill_name', 'content', 'scope', 'scope_ref', 'pattern_tags'])
  })

  it('triggers: 6 append-only guards kept, 2 FTS-sync triggers dropped', async () => {
    const kept = [
      'prevent_audit_update', 'prevent_audit_delete',
      'prevent_scheduler_audit_update', 'prevent_scheduler_audit_delete',
      'prevent_task_phase_acceptance_update', 'prevent_task_phase_acceptance_delete',
    ]
    const dropped = ['messages_after_insert', 'messages_after_delete']
    const rows = (await pg.sql`
      SELECT tgname FROM pg_trigger
      WHERE NOT tgisinternal AND tgrelid::regclass::text = ANY(${[
        'schedule_audit_logs', 'scheduler_audit_logs', 'task_phase_acceptances', 'messages',
      ]}::text[])
    `).map(r => r.tgname as string)
    expect(rows.sort()).toEqual(kept.sort())
    for (const t of dropped) expect(rows).not.toContain(t)

    // 保留触发器真的在挡 UPDATE（守卫没成哑弹）
    await expect(pg.sql`INSERT INTO task_phase_acceptances (id, task_id, phase_index, round_index, decision, decided_at)
      VALUES ('t-1', 'task-x', 0, 0, 'accepted', now())`).resolves.toBeTruthy()
    await expect(pg.sql`UPDATE task_phase_acceptances SET feedback = 'x' WHERE id = 't-1'`)
      .rejects.toThrow(/append-only/)
    await pg.sql`DELETE FROM task_phase_acceptances`.catch(() => { /* append-only 守卫同样挡 DELETE */ })
  })
})

    expect(list.some((r) => r.includes('/api/actuator'))).toBe(false)
    // 具体 method 的路由不允许重复注册（ALL 条目是 use()/route() 中间件挂载，合法可重）
    const concrete = list.filter((r) => !r.startsWith('ALL '))
    const dup = concrete.filter((v, i) => concrete.indexOf(v) !== i)
    expect(dup, '重复注册的 path+method: ' + dup.join(', ')).toEqual([])

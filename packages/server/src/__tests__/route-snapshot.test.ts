/**
 * 路由清单快照守卫 —— B0.5 收口票 §5 方案2（routes/agent 拆 assembler）的硬性护栏。
 *
 * 枚举 app 上全部已注册 path+method，排序后与内联快照逐位比对。
 * per-domain assembler 拆分前后本快照必须逐位相等 —— 注册顺序、路径、方法
 * 任何一位漂移都会在这里红掉，比任何 review 可靠。
 *
 * 维护规则：只有当路由**本身**增删改（正常开发）才更新快照；
 * 纯重构类 PR 里本文件出现 diff = 该 PR 不干净。
 */
import { describe, it, expect } from 'vitest'
import app from '../index'

/** 排序后的 `METHOD path` 全量清单。 */
function routeList(): string[] {
  return app.routes.map((r) => `${r.method} ${r.path}`).sort()
}


/**
 * DAG 画布的方向词表 —— 与 dagre 的 `rankdir` 用同一组字面量（"LR" / "TB"），
 * 所以布局算出来的流向和节点组件挂边（Handle）的方向不会各说各话。
 *
 * 为什么不是整张图一刀切一个方向（2026-10-30 定稿）：
 * - **主干 LR（横向）**：阶段从左往右读，和「宽视口 + 长流水线」同形状。
 *   原先 TB 时一条 7 阶段链是 400×2800 的瘦高条，fitView 只能按高度缩到 ~25%，
 *   整图糊成一团；横向后按宽度缩，同样的画布能多放一倍节点。
 * - **容器体内 TB（纵向）**：loop / 子工作流的体内节点仍自上而下。一个装了 10 张
 *   ticket 的子工作流若也走 LR，容器会被撑成 ~3000px 宽的怪物盒子，反过来把主干
 *   挤到看不清楚；纵向压成主干上的一列，宽高都留在可读区间。
 *
 * 落点：workflow-parser 把方向写进每个节点的 `data.dagOrientation`，节点组件用
 * `components/workspace/workflow-nodes/dag-handles` 里的同一张映射表决定进出边挂
 * 哪条边 —— 布局与外观只有这一个来源，不会漂移。
 */
export type DagOrientation = "LR" | "TB"

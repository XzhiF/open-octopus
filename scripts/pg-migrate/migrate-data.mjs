#!/usr/bin/env node
/**
 * P1-B1 · 74MB 存量数据一次性搬迁：SQLite → PostgreSQL（COPY），幂等可重跑。
 *
 * 用法:
 *   node scripts/pg-migrate/migrate-data.mjs --db <sqlite> --pg <pg-url>
 *        [--dry-run | --verify-only] [--quarantine] [--report <out.md>] [--sample <n=5>]
 *
 *   --dry-run      校验 + 对账预演（逐表行数/脏清单/装载序），零写入
 *   --verify-only  不装载，只对当前 PG 现状跑对账（重跑幂等验证用）
 *   --quarantine   脏行（不可解析 jsonb / 坏时间戳 / NOT NULL 存 NULL / 布尔域外 /
 *                  FK 孤儿及其级联）整行进隔离清单，其余照常灌；脏清单必进报告
 *
 * 契约 → 实现落点：
 *   1) 幂等：单事务 TRUNCATE <全部表> RESTART IDENTITY CASCADE 后按依赖序全量重灌；
 *      任何一步失败 → 整体回滚，PG 停在上次成功态；任意次重跑结果一致。
 *   2) 带原 id：PG IDENTITY 为 GENERATED BY DEFAULT（B0 铺路，见 db/pg/schema.sql 头注），
 *      COPY 列清单带原主键；提交后对全部 attidentity='d' 列 setval —— 表达式与
 *      db/pg/migrate.ts 同款（COALESCE(MAX(id),0)+1, is_called=false），但动态发现，
 *      未来新增 IDENTITY 表自动覆盖。
 *   3) 类型转换按 B0 映射事实（db/pg/__tests__/schema-parity.test.ts 的
 *      JSONB/BOOL/EPOCH_MS/IDENTITY + isIsoTimestampCol；目标类型以 PG
 *      information_schema 实测为唯一真相源）：
 *        · epoch ms → bigint 直传（值域逐格校验）
 *        · TEXT 时间戳 → timestamptz：装载事务先 `SET timezone='UTC'`（schema.sql
 *          头注的坑：库内混存 toISOString 带 Z 与 datetime('now') 无标记 UTC 串；
 *          带标记串 PG 按标记解析，无标记串按会话 UTC 解读）
 *        · jsonb 列灌前 JSON.parse 校验，不可解析 → 行级清单，绝不静默丢
 *        · 布尔契约 0/1（B0 README 点名 0/1→bool 为最大静默漂移面），域外值进脏清单
 *   4) 表依赖序：对 PG 实际 FK 边（pg_constraint）做 Kahn 拓扑，父先于子；并列按
 *      表名字典序 → 跨运行确定。依据：FK 边两侧一一对由 B0 schema-parity 测试保证。
 *      FK 孤儿灌前全量检出并沿拓扑级联（父行被隔离 → 引用它的子行也成孤儿）。
 *   5) 对账（plan.html P1 判据③「逐表行数 + 抽样列值比对通过，不是跑起来了」）：
 *      ① 逐表行数双式核验：pg = 存活数 且 sqlite 总 = 存活 + 隔离；
 *      ② 每表 sha256 稳定排序抽 ≥5 行（不足取全表），比对全部映射列的归一化值
 *        （时间戳→epoch-ms、JSON→稳定序列化、布尔/整数/浮点归一、文本逐字）。
 *      不一致清单非空 → exit 1。
 *
 * exit code：0 零脏+全等 · 1 失败（严格模式脏数据零写入 / 对账不一致 / COPY 被拒）
 *            · 2 带隔离完成（--quarantine 下对账全等，脏清单见报告 —— 喂 P3）
 *
 * 只读纪律：SQLite 侧 better-sqlite3 readonly，全程零写。
 */

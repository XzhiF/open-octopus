// ── CLI ─────────────────────────────────────────────────────────────────────
function parseArgs(argv) {
  const out = { sample: 5, dryRun: false, verifyOnly: false, quarantine: false }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--db') out.db = argv[++i]
    else if (a === '--pg') out.pg = argv[++i]
    else if (a === '--dry-run') out.dryRun = true
    else if (a === '--verify-only') out.verifyOnly = true
    else if (a === '--quarantine') out.quarantine = true
    else if (a === '--report') out.report = argv[++i]
    else if (a === '--sample') {
      out.sample = Number(argv[++i])
      if (!Number.isInteger(out.sample) || out.sample < 1) die('--sample 需为正整数')
    } else if (a === '--help' || a === '-h') {
      console.log('用法: migrate-data.mjs --db <sqlite> --pg <url> [--dry-run|--verify-only] [--quarantine] [--report <md>] [--sample <n>]')
      process.exit(0)
    } else die(`未知参数: ${a}`)
  }
  if (!out.db || !out.pg) die('必须提供 --db <sqlite路径> 与 --pg <pg-url>')
  if (out.dryRun && out.verifyOnly) die('--dry-run 与 --verify-only 互斥')
  return out
}
function die(msg) { console.error('[pg-migrate]', msg); process.exit(1) }

// ── PG 元数据（目标类型 = 唯一真相源；B0 parity 保证与 SQLite 侧一致）────────
async function loadPgMeta(sql) {
  const colRows = await sql`
    SELECT table_name, column_name, data_type, is_nullable = 'NO' AS notnull,
           column_default IS NOT NULL AS hasdefault
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name <> 'octopus_schema_version'
      AND table_name NOT LIKE 'pg\\_%' ESCAPE '\\'
      AND table_name NOT LIKE '%\\_fts%' ESCAPE '\\'
      -- P1 B4 票2B-2: information_schema.columns 同样列出视图列（如 llm_calls_costed
      -- 派生视图）—— 视图不可 TRUNCATE/COPY，枚举只认 BASE TABLE。
      AND table_name IN (
        SELECT table_name FROM information_schema.tables
        WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
      )
    ORDER BY table_name, ordinal_position`
  const fkRows = await sql`
    SELECT src.relname AS child, tgt.relname AS parent,
           (SELECT a.attname FROM pg_attribute a WHERE a.attrelid = fc.conrelid AND a.attnum = fc.conkey[1]) AS ccol,
           (SELECT a.attname FROM pg_attribute a WHERE a.attrelid = fc.confrelid AND a.attnum = fc.confkey[1]) AS pcol
    FROM pg_constraint fc
    JOIN pg_class src ON src.oid = fc.conrelid
    JOIN pg_class tgt ON tgt.oid = fc.confrelid
    WHERE fc.contype = 'f'`
  const identRows = await sql`
    SELECT c.relname AS t, a.attname AS c
    FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND a.attidentity = 'd' AND a.attnum > 0
    ORDER BY 1, 2`
  const placeholderRows = await sql`
    SELECT table_name FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name LIKE '%\\_fts%' ESCAPE '\\'`
  const tables = new Map()
  for (const r of colRows) {
    if (!tables.has(r.table_name)) tables.set(r.table_name, [])
    tables.get(r.table_name).push({ name: r.column_name, type: r.data_type, notnull: r.notnull, hasdefault: r.hasdefault })
  }
  const fks = fkRows
    .filter((r) => r.child !== r.parent && tables.has(r.child) && tables.has(r.parent))
    .map((r) => ({ child: r.child, parent: r.parent, ccol: r.ccol, pcol: r.pcol }))
  return { tables, fks, identities: identRows.map((r) => [r.t, r.c]), placeholders: placeholderRows.map((r) => r.table_name) }
}

// Kahn 拓扑排序（父表先装载；并列字典序 —— 依赖序跨运行确定）
function topoOrder(tables, fks) {
  const indeg = new Map([...tables.keys()].map((t) => [t, 0]))
  const children = new Map()
  for (const { child, parent } of fks) {
    indeg.set(child, indeg.get(child) + 1)
    if (!children.has(parent)) children.set(parent, [])
    children.get(parent).push(child)
  }
  const ready = [...indeg.entries()].filter(([, d]) => d === 0).map(([t]) => t).sort()
  const order = []
  while (ready.length) {
    const t = ready.shift()
    order.push(t)
    for (const c of (children.get(t) ?? []).sort()) {
      const d = indeg.get(c) - 1
      indeg.set(c, d)
      if (d === 0) { ready.push(c); ready.sort() }
    }
  }
  if (order.length !== tables.size) throw new Error(`FK 拓扑存在环（排出 ${order.length} / 应 ${tables.size}）`)
  return order
}

// ── 值归一（灌前校验、COPY 编码、对账比较共用同一套语义）─────────────────────
// normValue: pgType + 任一引擎原值 → 跨侧可比的字符串（epoch-ms / 稳定 JSON / 归一文本）。
function normValue(pgType, raw) {
  if (raw === null || raw === undefined) return null
  switch (pgType) {
    case 'timestamp with time zone': {
      if (raw instanceof Date) return String(raw.getTime())
      const iso = String(raw).replace(' ', 'T')
      const marked = /[zZ]$|[+-]\d{2}:?\d{2}$/.test(iso)
      const ms = Date.parse(marked ? iso : iso + 'Z') // 无标记串按 UTC —— 与装载会话 SET timezone='UTC' 同纪律
      return Number.isNaN(ms) ? `UNPARSED:${String(raw)}` : String(ms)
    }
    case 'jsonb':
      return stableJson(typeof raw === 'string' ? safeParse(raw) : raw)
    case 'boolean':
      if (typeof raw === 'boolean') return raw ? '1' : '0'
      return String(Number(raw))
    case 'bigint': case 'integer':
      return String(raw)
    case 'double precision':
      return String(Number(raw))
    default:
      if (Buffer.isBuffer(raw)) return `BLOB:${sha(Buffer.from(raw))}`
      return String(raw)
  }
}
function safeParse(s) { try { return JSON.parse(s) } catch { return { __raw: s } } }
function stableJson(v) {
  if (v === null || v === undefined) return 'null'
  if (Array.isArray(v)) return '[' + v.map(stableJson).join(',') + ']'
  if (typeof v === 'object')
    return '{' + Object.keys(v).sort().map((k) => JSON.stringify(k) + ':' + stableJson(v[k])).join(',') + '}'
  return JSON.stringify(v)
}

// cellIssue: 单格灌前判定。null = 可安全入 PG；否则行级脏原因。
function cellIssue(col, raw) {
  const { type, notnull } = col
  if (raw === null || raw === undefined) return notnull ? 'null-in-notnull' : null
  if (Buffer.isBuffer(raw)) return 'binary-value'
  if (typeof raw === 'string' && raw.includes('\0')) return 'nul-byte'
  switch (type) {
    case 'jsonb':
      if (typeof raw !== 'string') return 'json-col-non-text'
      try { JSON.parse(raw); return null } catch { return 'json-col-unparseable' }
    case 'timestamp with time zone':
      if (typeof raw === 'number') return 'ts-col-numeric-epoch' // EPOCH_MS 列在 B0 映射里是 bigint —— 落 timestamptz 即脏
      if (typeof raw !== 'string') return 'ts-col-non-text'
      {
        const iso = raw.replace(' ', 'T')
        const marked = /[zZ]$|[+-]\d{2}:?\d{2}$/.test(iso)
        return Number.isNaN(Date.parse(marked ? iso : iso + 'Z')) ? 'ts-col-unparseable' : null
      }
    case 'boolean':
      if (typeof raw === 'number' && (raw === 0 || raw === 1)) return null
      if (typeof raw === 'bigint' && (raw === 0n || raw === 1n)) return null
      if (typeof raw === 'string' && (raw === '0' || raw === '1')) return null
      return 'bool-col-not-01'
    case 'integer': case 'bigint': {
      const lo = type === 'bigint' ? -9223372036854775808n : -2147483648n
      const hi = type === 'bigint' ? 9223372036854775807n : 2147483647n
      let v
      if (typeof raw === 'number') {
        if (!Number.isInteger(raw)) return 'int-col-non-integer'
        if (!Number.isSafeInteger(raw)) return 'int-col-unsafe-precision'
        v = BigInt(raw)
      } else if (typeof raw === 'bigint') v = raw
      else if (typeof raw === 'string' && /^-?\d+$/.test(raw)) v = BigInt(raw)
      else return 'int-col-non-numeric'
      return v < lo || v > hi ? 'int-col-out-of-range' : null
    }
    case 'double precision':
      if (typeof raw === 'number') return Number.isFinite(raw) ? null : 'float-col-non-finite'
      if (typeof raw === 'bigint') return null
      if (typeof raw === 'string' && raw.trim() !== '' && Number.isFinite(Number(raw))) return null
      return 'float-col-non-numeric'
    default:
      return null // text：非 BLOB 非 NUL 皆合法
  }
}

// ── 表形状：PG 列 ∩ SQLite 列；主键；双向漂移清单 ────────────────────────────
function tableShape(db, table, pgCols) {
  const sCols = db.prepare(`PRAGMA table_info("${table}")`).all()
  const pk = sCols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk).map((c) => c.name)
  if (pk.length === 0) throw new Error(`${table}: SQLite 无主键 —— 无法定位脏行`)
  const present = new Set(sCols.map((c) => c.name))
  return {
    pk,
    use: pgCols.filter((c) => present.has(c.name)),
    pgOnly: pgCols.filter((c) => !present.has(c.name)),
    sqliteOnly: sCols.filter((c) => !pgCols.some((p) => p.name === c.name)).map((c) => c.name),
  }
}

// ── 校验 pass（只读）：逐表逐格 → 行级脏清单 + 隔离集 + 抽样池 ────────────────
function validateTable(db, table, shape) {
  const rows = db.prepare(`SELECT ${shape.use.map((c) => `"${c.name}"`).join(', ')} FROM "${table}"`).all()
  const problems = []
  const dirty = new Set()
  const seen = new Set()
  // pgOnly 列（PG 有、SQLite 无源）：可空/有 DEFAULT → 装载即 NULL/默认值（合法）；
  // NOT NULL 且无默认 → 每行必脏（无法凭空造值）。
  const pgOnlyNotNull = shape.pgOnly.filter((c) => c.notnull && !c.hasdefault)
  for (const row of rows) {
    const pkVal = shape.pk.map((k) => String(row[k])).join(PK_SEP)
    for (const col of shape.use) {
      const why = cellIssue(col, row[col.name])
      if (why) {
        problems.push({ table, pk: pkVal, column: col.name, kind: why, value: trunc(String(row[col.name])) })
        dirty.add(pkVal)
      }
    }
    for (const col of pgOnlyNotNull) {
      problems.push({ table, pk: pkVal, column: col.name, kind: 'pg-col-no-sqlite-source', value: 'NOT NULL 但 SQLite 无此列' })
      dirty.add(pkVal)
    }
    if (seen.has(pkVal)) {
      problems.push({ table, pk: pkVal, column: shape.pk.join(','), kind: 'duplicate-pk', value: '第二次出现' })
      dirty.add(pkVal)
    }
    seen.add(pkVal)
  }
  const pool = rows.map((r) => shape.pk.map((k) => String(r[k])).join(PK_SEP))
    .filter((p) => !dirty.has(p))
  return { rows, pk: shape.pk, dirty, pool, problems }
}

// FK 孤儿（含级联）：按拓扑序扫 —— 父表 pool 先定型，子表引用不存在的父行即脏；
// 子表自身被隔离又会使其子表成孤儿（同一趟覆盖，因为父先于子）。
function orphanSweep(db, order, shapes, vals, fkByChild) {
  const problems = []
  for (const child of order) {
    const v = vals.get(child)
    const shape = shapes.get(child)
    for (const fk of fkByChild.get(child) ?? []) {
      const pv = vals.get(fk.parent)
      if (!pv) continue // 父表不在 SQLite 源（0 行）→ 子表任何非空引用都是孤儿，parentSet 为空集即可
      const parentSet = new Set(pv.pool)
      for (const row of v.rows) {
        const pkVal = shape.pk.map((k) => String(row[k])).join(PK_SEP)
        if (v.dirty.has(pkVal)) continue
        const fv = row[fk.ccol]
        if (fv === null || fv === undefined) continue
        if (!parentSet.has(String(fv))) {
          v.dirty.add(pkVal)
          v.pool = v.pool.filter((p) => p !== pkVal)
          problems.push({ table: child, pk: pkVal, column: fk.ccol, kind: 'fk-orphan', value: `-> ${fk.parent}.${fk.pcol} = ${trunc(String(fv))}` })
        }
      }
    }
  }
  return problems
}

// ── COPY 文本编码 ────────────────────────────────────────────────────────────
const COPY_ESC = { '\\': '\\\\', '\t': '\\t', '\n': '\\n', '\r': '\\r' }
const escField = (s) => String(s).replace(/[\\\t\n\r]/g, (c) => COPY_ESC[c])
function copyLine(row, cols) {
  const parts = new Array(cols.length)
  for (let i = 0; i < cols.length; i++) {
    const col = cols[i]
    const raw = row[col.name]
    if (raw === null || raw === undefined) { parts[i] = '\\N'; continue }
    let v = raw
    if (col.type === 'timestamp with time zone' && typeof v === 'string') v = v.replace(' ', 'T') // 空格分隔是合法输入，T 更无歧义
    if ((col.type === 'integer' || col.type === 'bigint')) {
      if (typeof v === 'string') v = String(BigInt(v))
      else if (typeof v === 'number') v = Math.trunc(v)
    }
    parts[i] = escField(v)
  }
  return parts.join('\t') + '\n'
}

// ── 装载：手动 BEGIN/COMMIT（max:1 连接），失败整体回滚（幂等的根基） ──────────
// 为什么不用 sql.begin()：begin 的 scope 会对每条查询内部挂 q.catch 记 uncaughtError，
// 即使调用方已处理 COPY_IN_PROGRESS 探测拒绝，COMMIT 时也会被 scope 重抛成失败
// （postgres.js 3.4.9 对照实验 18/18 复现）。max:1 + simple BEGIN/COMMIT 绕开 scope，
// 探测 rejection 归调用方 catch 独享；connection.js:605 保证 max:1 下 BEGIN 合法。
async function loadAll(sql, order, shapes, vals, db, meta) {
  const loaded = new Map()
  await sql`SET timezone = 'UTC'`      // schema.sql 头注的坑：无标记 UTC 串按会话时区解读 —— 锁 UTC
  await sql`SET statement_timeout = 0` // 搬迁连接豁免查询级超时（B0 pool.ts 头注：server 级刻意不设）
  await sql`BEGIN`
  try {
    await sql.unsafe(
      `TRUNCATE TABLE ${[...shapes.keys(), ...meta.placeholders].map((t) => `"${t}"`).join(', ')} RESTART IDENTITY CASCADE`)
    for (const table of order) {
      const shape = shapes.get(table)
      const v = vals.get(table)
      if (!v.rows.length) { loaded.set(table, 0); continue } // 空表/缺源表：0 行 COPY 省掉（也避免空列清单）
      const colList = shape.use.map((c) => `"${c.name}"`).join(', ')
      const stream = await sql.unsafe(`COPY "${table}" (${colList}) FROM STDIN (FORMAT text)`).writable()
      let n = 0
      let buf = []
      for (const row of v.rows) {
        const pkVal = shape.pk.map((k) => String(row[k])).join(PK_SEP)
        if (v.dirty.has(pkVal)) continue
        buf.push(copyLine(row, shape.use))
        n++
        if (buf.length >= 1000) { stream.write(buf.join('')); buf = [] }
      }
      if (buf.length) stream.write(buf.join(''))
      stream.end()
      await waitCopySettled(sql, stream, table)
      loaded.set(table, n)
      log(`  COPY ${table}: ${n} 行（隔离 ${v.rows.length - n}）`)
    }
    await sql`COMMIT`
  } catch (e) {
    await sql`ROLLBACK`.catch(() => {})
    throw e
  }
  return loaded
}
// COPY 完成判定（postgres.js 3.4.9 实测纪律）：
//   · 唯一成功信号 = stream 的 'finish'（= COPY 的 CommandComplete 已被连接层消费）。
//   · PG 拒 COPY 时 finish 永不到达 → 探测语句区分：COPY_IN_PROGRESS=数据还在刷；
//     25P02=被拒（大声失败，外层 ROLLBACK）。autoDestroy=false 掐掉 finish 后的杂散 CopyFail。
async function waitCopySettled(sql, stream, table) {
  stream.autoDestroy = false
  const done = new Promise((res) => stream.once('finish', () => res(true)))
  const deadline = Date.now() + 600_000
  for (;;) {
    const ok = await Promise.race([done, sleep(200).then(() => false)])
    if (ok === true) return
    try { await sql`SELECT 1` }
    catch (e) {
      if (e.code === 'COPY_IN_PROGRESS') { /* CopyData 仍在刷出，继续等 finish */ }
      else if (e.code === '25P02') throw new Error(`${table}: COPY 被 PG 拒绝（前置校验漏网行）—— 事务回滚`)
      else throw e
    }
    if (Date.now() > deadline) throw new Error(`${table}: COPY 等待超时（>10min）`)
  }
}

// IDENTITY 序列对齐（与 db/pg/migrate.ts setval 表达式同款；动态发现全部 attidentity='d'）
async function syncIdentitySequences(sql, identities) {
  for (const [t, c] of identities)
    await sql.unsafe(
      `SELECT setval(pg_get_serial_sequence('${t}', '${c}'), ` +
      `(SELECT COALESCE(MAX("${c}"), 0) + 1 FROM "${t}"), false)`)
  return identities.length
}

// ── 对账 ─────────────────────────────────────────────────────────────────────
async function reconcile(sql, db, order, shapes, vals, sampleN, sSet) {
  const rowsOut = []
  const mismatches = []
  for (const table of order) {
    const shape = shapes.get(table)
    const v = vals.get(table)
    const quarantined = v.rows.length - v.pool.length
    const sN = sSet.has(table) ? db.prepare(`SELECT count(*) AS c FROM "${table}"`).get().c : 0
    let pN
    try { pN = Number((await sql.unsafe(`SELECT count(*)::bigint AS c FROM "${table}"`))[0].c) }
    catch { pN = -1 }
    // 双式核验：pg=存活数 且 sqlite总=存活+隔离（存活+隔离 恒等于 sN 时第二式防「sqlite 侧读挂」）
    const rowsOk = pN === v.pool.length && sN === v.rows.length
    rowsOut.push({ table, sqlite: sN, quarantined, loaded: v.pool.length, pg: pN, ok: rowsOk })
    if (!rowsOk)
      mismatches.push({ table, pk: '(表级)', column: '*', kind: 'row-count',
        sqlite: `存活 ${v.pool.length} / 总 ${v.rows.length} / 隔离 ${quarantined}`, pg: String(pN) })
    const picked = topSample(v.pool, sampleN)
    let cmp = 0
    for (const pkVal of picked) {
      const sRow = fetchByPkSqlite(db, table, shape.pk, pkVal)
      if (!sRow) { mismatches.push({ table, pk: pkVal, column: '*', kind: 'sqlite-row-missing', sqlite: '?', pg: '?' }); continue }
      const pRow = await fetchByPkPg(sql, table, shape.pk, pkVal)
      if (!pRow) { mismatches.push({ table, pk: pkVal, column: '*', kind: 'pg-row-missing', sqlite: 'row', pg: 'MISSING' }); continue }
      for (const col of shape.use) {
        cmp++
        const sv = normValue(col.type, sRow[col.name])
        const pv = normValue(col.type, pRow[col.name])
        if (sv !== pv)
          mismatches.push({ table, pk: pkVal, column: col.name, kind: 'value', sqlite: trunc(String(sv)), pg: trunc(String(pv)) })
      }
    }
    log(`  对账 ${table}: 总${v.rows.length} 隔离${quarantined} pg${pN}${rowsOk ? ' ✓' : ' ✗'} · 抽样 ${picked.length} 行/${cmp} 格`)
  }
  return { rowsOut, mismatches }
}
function topSample(pool, n) {
  return [...pool].map((v) => ({ v, h: sha(String(v)) }))
    .sort((a, b) => (a.h < b.h ? -1 : a.h > b.h ? 1 : 0))
    .slice(0, n).map((x) => x.v)
}
function splitPk(pkVal, len) {
  const parts = String(pkVal).split(PK_SEP)
  return parts.length === len ? parts : null
}
function fetchByPkSqlite(db, table, pk, pkVal) {
  const parts = splitPk(pkVal, pk.length)
  if (!parts) return null
  const where = pk.map((k) => `"${k}" = ?`).join(' AND ')
  return db.prepare(`SELECT * FROM "${table}" WHERE ${where} LIMIT 1`).get(...parts) ?? null
}
async function fetchByPkPg(sql, table, pk, pkVal) {
  const parts = splitPk(pkVal, pk.length)
  if (!parts) return null
  const where = pk.map((k, i) => `"${k}" = $${i + 1}`).join(' AND ')
  const rows = await sql.unsafe(`SELECT * FROM "${table}" WHERE ${where} LIMIT 1`, parts)
  return rows[0] ?? null
}

// 装载后 PG 侧 FK 复核（双保险 + 报告证据：PG 约束视角 0 孤儿）
async function fkCheck(sql, fks) {
  const out = []
  for (const { child, parent, ccol, pcol } of fks) {
    const orphans = await sql.unsafe(
      `SELECT ch."${ccol}" AS v FROM "${child}" ch WHERE ch."${ccol}" IS NOT NULL
         AND NOT EXISTS (SELECT 1 FROM "${parent}" p WHERE p."${pcol}" = ch."${ccol}") LIMIT 50`)
    for (const o of orphans)
      out.push({ table: child, pk: String(o.v), column: ccol, kind: 'fk-orphan-in-pg', value: `-> ${parent}.${pcol}` })
  }
  return out
}

// ── 漂移观察（只报不丢）──────────────────────────────────────────────────────
function collectNotes(db, shapes, sqliteTableNames) {
  const notes = []
  for (const [table, shape] of shapes) {
    for (const c of shape.pgOnly)
      notes.push({ table, kind: 'pg-col-no-sqlite-source',
        detail: `${c.name}${c.notnull && !c.hasdefault ? '（NOT NULL 无默认 —— 该行全量进脏清单）' : c.hasdefault ? '（装载取 PG 默认值）' : '（装载为 NULL）'}` })
    for (const c of shape.sqliteOnly) {
      const n = db.prepare(`SELECT count(*) AS c FROM "${table}" WHERE "${c}" IS NOT NULL`).get().c
      notes.push({ table, kind: 'sqlite-col-not-in-pg', detail: `${c}：非空 ${n} 行${n > 0 ? '（该列不随迁 —— B0 schema 无此列）' : '（全 NULL，无损）'}` })
    }
  }
  for (const t of sqliteTableNames)
    if (!shapes.has(t))
      notes.push({ table: t, kind: 'sqlite-table-not-migrated',
        detail: isFtsFamily(t) ? 'FTS5 家族 —— pg_search 票在真表重建，无搬迁消费者'
          : isLegacyBackup(t) ? '历史 schema 备份表' : 'PG schema 无此表' })
  return notes
}

